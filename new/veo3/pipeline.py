def extract_clean_object(img: np.ndarray, binary_mask: np.ndarray) -> np.ndarray:
    contours, _ = cv2.findContours(binary_mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
    if not contours: return None
    main_contour = max(contours, key=cv2.contourArea)
    clean_mask = np.zeros_like(binary_mask)
    cv2.drawContours(clean_mask, [main_contour], -1, 255, thickness=cv2.FILLED)
    b, g, r = cv2.split(img)
    bgra = cv2.merge([b, g, r, clean_mask])
    ys, xs = np.where(clean_mask > 0)
    if len(xs) == 0: return None
    return bgra[ys.min():ys.max(), xs.min():xs.max()]

