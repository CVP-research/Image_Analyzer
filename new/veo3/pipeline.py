def step_1_select_best_views(input_dir: Path, poses_file: Path, num_views: int = 3) -> List[Path]:
    logger.info("--- Step 1: Selecting Best Views ---")
    input_images = [p for p in input_dir.glob("*") if p.suffix.lower() in {'.jpg', '.png', '.jpeg'}]
    if not input_images:
        logger.error(f"No images found in {input_dir}. Aborting.")
        return []
    poses = load_camera_poses(poses_file)
    if not poses:
        logger.warning("Could not load poses. Falling back to random selection.")
        return random.sample(input_images, min(num_views, len(input_images)))
    center = compute_center(poses)
    view_infos = []
    for filename, p in poses.items():
        if not (input_dir / filename).exists(): continue
        azimuth, elevation, distance = compute_azimuth_elevation(p["position"], center)
        az_rad, el_rad = math.radians(azimuth), math.radians(elevation)
        x, y, z = math.cos(el_rad) * math.sin(az_rad), math.sin(el_rad), math.cos(el_rad) * math.cos(az_rad)
        view_infos.append({"filename": filename, "azimuth": azimuth, "elevation": elevation, "vec": (x, y, z)})
    filtered = [v for v in view_infos if abs(v["elevation"]) <= 30.0]
    if len(filtered) < num_views:
        logger.warning(f"Only {len(filtered)} views within ±30° elevation. Using all available.")
        filtered = sorted(view_infos, key=lambda v: abs(v["elevation"]))[:max(num_views, len(view_infos))]
    ideal_positions = [(0, 0), (120, 0), (-120, 0)]
    close_to_ideal_count = sum(1 for az, el in ideal_positions for v in filtered if min(abs(v["azimuth"] - az), 360 - abs(v["azimuth"] - az)) < 25 and abs(v["elevation"] - el) < 15)
    strategy = _fixed_grid_selection if close_to_ideal_count >= 2 else _robust_greedy_selection
    logger.info(f"View distribution detected. Using {strategy.__name__} strategy.")
    chosen_views = strategy(filtered, ideal_positions) if strategy == _fixed_grid_selection else strategy(filtered)
    chosen_filenames = {v["filename"] for v in chosen_views}
    selected_paths = [p for p in input_images if p.name in chosen_filenames]
    logger.info(f"Selected {len(selected_paths)} views: {[p.name for p in selected_paths]}")
    return selected_paths

def step_2_process_video(video_path: Path, output_dir: Path) -> Path:
    logger.info("--- Step 2: Processing VEO3 Video ---")
    unique_frames_dir = output_dir / "1_unique_frames"
    segmented_objects_dir = output_dir / "2_segmented_objects"
    frame_from_video(video_path, unique_frames_dir)
    step_2b_segment_frames(unique_frames_dir, segmented_objects_dir)
    logger.info("Step 2 finished.")
    return segmented_objects_dir

def step_2b_segment_frames(frames_dir: Path, segmented_output_dir: Path):
    logger.info(f"--- Step 2b: Segmenting frames from {frames_dir} ---")
    segmented_output_dir.mkdir(parents=True, exist_ok=True)
    model = get_sam_model()
    if model is None: return
    frame_paths = sorted([p for p in frames_dir.iterdir() if p.suffix.lower() in {'.jpg', '.png', '.jpeg'}])
    if not frame_paths:
        logger.warning(f"No frames found in {frames_dir} to segment.")
        return
    logger.info(f"Found {len(frame_paths)} frames. Starting batch segmentation...")
    for i in tqdm(range(0, len(frame_paths), 16), desc="Segmenting Batches"):
        batch_paths = frame_paths[i:i+16]
        try:
            results = model.predict(batch_paths, task="segment", verbose=False)
            for frame_path, result in zip(batch_paths, results):
                if result.masks is None: continue
                original_image = cv2.imread(str(frame_path))
                if original_image is None: continue
                for mask_idx, mask in enumerate(result.masks.data):
                    obj_cropped = extract_clean_object(original_image, mask.cpu().numpy().astype(np.uint8) * 255)
                    if obj_cropped is not None:
                        cv2.imwrite(str(segmented_output_dir / f"{frame_path.stem}_obj_{mask_idx}.png"), obj_cropped)
        except Exception as e:
            logger.error(f"Error on segmentation batch starting with {batch_paths[0].name}: {e}")
    logger.info(f"Segmentation complete. Masked objects saved to {segmented_output_dir}")

def step_3_generate_data(segmented_objects_dir: Path, background_dir: Path, output_dir: Path, num_positives: int, num_negatives: int, class_name: str):
    logger.info("--- Step 3: Generating Synthetic Data ---")
    builder = DatasetBuilder(
        obj_root=segmented_objects_dir, 
        bg_root=background_dir, 
        output_root=output_dir, 
        class_id=0 # Assuming single class for now
    )
    builder.generate(num_positives=num_positives, num_negatives=num_negatives, class_name=class_name)

