class DatasetBuilder:
    def __init__(self, obj_root, bg_root, output_root, class_id=0, target_size=1024, tile_size=256, val_split_ratio=0.2):
        self.obj_root = obj_root
        self.bg_root = bg_root
        self.output_root = output_root
        self.class_id = class_id
        self.target_size = target_size
        self.tile_size = tile_size
        self.val_split_ratio = val_split_ratio
        
        logger.info("🚀 Loading Image Harmonization Model...")
        self.harmonization_net = image_harmonization.ImageHarmonizationModel(device=0)
        self.object_files = self._load_files(self.obj_root, ('*.png',))
        self.bg_paths = self._load_files(self.bg_root, ('*.jpg', '*.png', '*.jpeg'))
        logger.info(f"Loaded {len(self.object_files)} objects and {len(self.bg_paths)} backgrounds.")

    def _load_files(self, root_dir, extensions):
        return [p for ext in extensions for p in Path(root_dir).rglob(ext)]

    def _create_tiled_bg(self, bg_paths_chunk):
        rows = []
        for i in range(0, 16, 4):
            cols = []
            for j in range(4):
                try:
                    img = cv2.imread(str(bg_paths_chunk[i+j]))
                    img = cv2.resize(img, (self.tile_size, self.tile_size)) if img is not None else np.zeros((self.tile_size, self.tile_size, 3), np.uint8)
                except Exception:
                    img = np.zeros((self.tile_size, self.tile_size, 3), np.uint8)
                cols.append(img)
            rows.append(np.hstack(cols))
        return np.vstack(rows)

    def _get_tiled_backgrounds(self, target_count):
        if not self.bg_paths:
            raise ValueError("No background images found.")
        if len(self.bg_paths) < 16:
             raise ValueError(f"Not enough background images for even one tile! Need 16, have {len(self.bg_paths)}.")
        
        num_tiles_possible = len(self.bg_paths) // 16
        if num_tiles_possible < target_count:
            logger.warning(f"Not enough unique backgrounds to create {target_count} tiles. Will reuse backgrounds.")
            bg_chunks = [random.sample(self.bg_paths, 16) for _ in range(target_count)]
        else:
            random.shuffle(self.bg_paths)
            bg_chunks = [self.bg_paths[i:i+16] for i in range(0, target_count * 16, 16)]

        return [self._create_tiled_bg(chunk) for chunk in tqdm(bg_chunks, desc="Tiling backgrounds")]

    def _get_yolo_label(self, mask):
        contours, _ = cv2.findContours(mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
        if not contours: return None
        cnt = max(contours, key=cv2.contourArea)
        epsilon = 0.0001 * cv2.arcLength(cnt, True)
        approx = cv2.approxPolyDP(cnt, epsilon, True)
        if len(approx) < 3: return None
        points_str = [f"{(p[0][0]/self.target_size):.6f} {(p[0][1]/self.target_size):.6f}" for p in approx]
        return f"{self.class_id} " + " ".join(points_str)

    def _process_and_save(self, bg, split_name, filename, is_positive):
        img_path = self.output_root / 'images' / split_name / f"{filename}.jpg"
        lbl_path = self.output_root / 'labels' / split_name / f"{filename}.txt"
        if not is_positive:
            cv2.imwrite(str(img_path), bg)
            lbl_path.touch()
            return 1
        
        obj_path = random.choice(self.object_files)
        obj_img = cv2.imread(str(obj_path), cv2.IMREAD_UNCHANGED)
        if obj_img is None: return 0

        h, w = obj_img.shape[:2]
        scale = (random.uniform(0.15, 0.35) * self.target_size) / max(h, w) if max(h, w) > 0 else 1.0
        obj_img = cv2.resize(obj_img, (int(w * scale), int(h * scale)), interpolation=cv2.INTER_AREA)
        h_obj, w_obj = obj_img.shape[:2]
        if h_obj == 0 or w_obj == 0: return 0
        
        y_pos, x_pos = random.randint(0, self.target_size - h_obj), random.randint(0, self.target_size - w_obj)
        
        mask = np.zeros((self.target_size, self.target_size), dtype=np.uint8)
        
        if obj_img.shape[2] != 4:
            logger.warning(f"Object image {obj_path.name} does not have an alpha channel. Skipping.")
            return 0
        
        alpha = obj_img[:, :, 3]
        mask[y_pos:y_pos+h_obj, x_pos:x_pos+w_obj] = (alpha > 127) * 255
        
        label = self._get_yolo_label(mask)
        if not label: return 0
        
        composite = bg.copy()
        alpha_s = obj_img[:, :, 3] / 255.0
        alpha_s = np.dstack((alpha_s, alpha_s, alpha_s)) # Make it 3-channel
        
        composite_roi = composite[y_pos:y_pos+h_obj, x_pos:x_pos+w_obj]
        obj_bgr = obj_img[:, :, :3]
        
        composite_roi[:] = alpha_s * obj_bgr + (1.0 - alpha_s) * composite_roi
        
        harmonized = self.harmonization_net(cv2.cvtColor(composite, cv2.COLOR_BGR2RGB), mask)
        final_bgr = cv2.cvtColor(np.clip(harmonized * 255 if harmonized.max() <= 1.0 else harmonized, 0, 255).astype(np.uint8), cv2.COLOR_RGB2BGR)

        cv2.imwrite(str(img_path), final_bgr)
        with open(lbl_path, "w") as f: f.write(label + "\n")
        return 1

    def generate(self, num_positives, num_negatives, class_name):
        create_yolo_dataset_structure(self.output_root, [class_name])
        total_generated = 0
        
        if not self.object_files:
            logger.warning("No object files found. Skipping positive sample generation.")
            num_positives = 0
            
        if not self.bg_paths:
            logger.error("No background files found. Cannot generate any data.")
            return

        if num_positives > 0:
            try:
                pos_bgs = self._get_tiled_backgrounds(num_positives)
                split_idx = int(len(pos_bgs) * (1 - self.val_split_ratio))
                for bg, split in tqdm(zip(pos_bgs, ['train']*split_idx + ['val']*(len(pos_bgs)-split_idx)), total=len(pos_bgs), desc="Generating positive samples"):
                    total_generated += self._process_and_save(bg, split, f"positive_{total_generated:06d}", True)
            except ValueError as e:
                logger.error(f"Could not generate positive samples: {e}")

        if num_negatives > 0:
            try:
                neg_bgs = self._get_tiled_backgrounds(num_negatives)
                split_idx = int(len(neg_bgs) * (1 - self.val_split_ratio))
                for bg, split in tqdm(zip(neg_bgs, ['train']*split_idx + ['val']*(len(neg_bgs)-split_idx)), total=len(neg_bgs), desc="Generating negative samples"):
                    total_generated += self._process_and_save(bg, split, f"negative_{total_generated:06d}", False)
            except ValueError as e:
                logger.error(f"Could not generate negative samples: {e}")

        logger.info(f"✅✅✅ Generation complete! Total images created: {total_generated} ✅✅✅")


