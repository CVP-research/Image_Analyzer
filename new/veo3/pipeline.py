# --- Pose and View Selection Helpers ---

def load_camera_poses(path: Path) -> Dict[str, dict]:
    """Loads camera poses from a JSON file."""
    logger.info(f"Loading camera poses from {path}...")
    if not path.exists():
        logger.error(f"FATAL: Camera poses file not found at {path}")
        return None
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)

def compute_center(poses: Dict[str, dict]) -> List[float]:
    xs, ys, zs = [], [], []
    for p in poses.values():
        lx, ly, lz = p["look_at"]
        xs.append(lx)
        ys.append(ly)
        zs.append(lz)
    n = len(xs) if xs else 1
    return [sum(xs)/n, sum(ys)/n, sum(zs)/n]

def compute_azimuth_elevation(position: List[float], center: List[float]) -> tuple[float, float, float]:
    cx, cy, cz = center
    px, py, pz = position
    vx, vy, vz = px - cx, py - cy, pz - cz
    r = math.sqrt(vx*vx + vy*vy + vz*vz) + 1e-8
    azimuth = math.degrees(math.atan2(vx, vz))
    elevation = math.degrees(math.asin(vy / r))
    return azimuth, elevation, r

def _fixed_grid_selection(filtered: List[dict], ideal_positions: List[Tuple[float, float]]) -> List[dict]:
    chosen = []
    remaining = filtered.copy()
    for ideal_az, ideal_el in ideal_positions:
        if not remaining: break
        best = min(remaining, key=lambda v: math.sqrt((v["azimuth"] - ideal_az)**2 + (v["elevation"] - ideal_el)**2))
        chosen.append(best)
        remaining.remove(best)
    return sorted(chosen, key=lambda v: v["azimuth"])

def _robust_greedy_selection(filtered: List[dict]) -> List[dict]:
    def vec_distance(v1, v2):
        dot = sum(a * b for a, b in zip(v1["vec"], v2["vec"]))
        return math.degrees(math.acos(max(-1, min(1, dot))))
    if not filtered: return []
    first = min(filtered, key=lambda v: abs(v["azimuth"]) + abs(v["elevation"]) * 3.0)
    chosen = [first]
    remaining = [v for v in filtered if v is not first]
    if len(remaining) < 2: return chosen + remaining
    second = max(remaining, key=lambda v: vec_distance(first, v) - abs(v["elevation"]) * 2)
    chosen.append(second)
    remaining = [v for v in remaining if v is not second]
    if len(remaining) < 1: return chosen + remaining
    third = max(remaining, key=lambda v: min(vec_distance(first, v), vec_distance(second, v)) - abs(v["elevation"]) * 2)
    chosen.append(third)
    return sorted(chosen, key=lambda v: v["azimuth"])

# --- Video and Segmentation Helpers ---

def frame_from_video(video_path: Path, output_dir: Path):
    logger.info(f"Extracting unique frames from video: {video_path.name}")
    output_dir.mkdir(parents=True, exist_ok=True)
    cap = cv2.VideoCapture(str(video_path))
    seen_hashes = set()
    saved_idx = 0
    with tqdm(total=int(cap.get(cv2.CAP_PROP_FRAME_COUNT)), desc="Extracting frames") as pbar:
        while True:
            ret, frame = cap.read()
            if not ret: break
            pbar.update(1)
            frame_hash = hashlib.md5(frame.tobytes()).hexdigest()
            if frame_hash in seen_hashes: continue
            seen_hashes.add(frame_hash)
            cv2.imwrite(str(output_dir / f"frame_{saved_idx:04d}.png"), frame)
            saved_idx += 1
    cap.release()
    logger.info(f"Extracted {saved_idx} unique frames to {output_dir}")

